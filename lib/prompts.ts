export interface CompareBrief {
  mustHave?: string[];
  antiProfile?: string[];
  roleFrame?: string;
  keyTasks?: string[];
}

export function compareUser(
  brief: string,
  resumes: { name?: string; text: string }[],
  structured?: CompareBrief,
): string {
  const blocks = resumes
    .map((r, i) => `--- КАНДИДАТ ${i + 1}${r.name ? ` (${r.name})` : ""} ---\n${r.text}`)
    .join("\n\n");

  // Если позиция уже проанализирована — даём авторитетный структурированный бриф
  // (извлечённые must-have и анти-профиль), чтобы скоринг был точным, а не по прозе.
  const parts: string[] = [];
  if (structured?.roleFrame) parts.push(`РАМКА РОЛИ: ${structured.roleFrame}`);
  if (structured?.mustHave?.length) {
    parts.push(`MUST-HAVE (оценивай строго по этим пунктам):\n${structured.mustHave.map((m, i) => `${i + 1}. ${m}`).join("\n")}`);
  }
  if (structured?.antiProfile?.length) {
    parts.push(`АНТИ-ПРОФИЛЬ (стоп-факторы — проверь каждого кандидата):\n${structured.antiProfile.map((m, i) => `${i + 1}. ${m}`).join("\n")}`);
  }
  if (structured?.keyTasks?.length) {
    parts.push(`КЛЮЧЕВЫЕ ЗАДАЧИ (6–12 мес.):\n${structured.keyTasks.map((m) => `- ${m}`).join("\n")}`);
  }
  const structuredBlock = parts.length ? `СТРУКТУРИРОВАННЫЙ БРИФ:\n${parts.join("\n\n")}\n\n` : "";

  return `${structuredBlock}БРИФ / ТРЕБОВАНИЯ (контекст):\n"""\n${brief}\n"""\n\nРЕЗЮМЕ КАНДИДАТОВ:\n"""\n${blocks}\n"""\n\nОцени каждого относительно брифа (и, если задан, строго по структурированному must-have и анти-профилю) и верни JSON. Имя бери из резюме; если его нет — используй «Кандидат N».`;
}

