export function compareUser(brief: string, resumes: { name?: string; text: string }[]): string {
  const blocks = resumes
    .map((r, i) => `--- КАНДИДАТ ${i + 1}${r.name ? ` (${r.name})` : ""} ---\n${r.text}`)
    .join("\n\n");
  return `БРИФ / ТРЕБОВАНИЯ:\n"""\n${brief}\n"""\n\nРЕЗЮМЕ КАНДИДАТОВ:\n"""\n${blocks}\n"""\n\nОцени каждого относительно брифа и верни JSON. Имя бери из резюме; если его нет — используй «Кандидат N».`;
}

